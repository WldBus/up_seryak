-- База данных «Театральная касса» (PostgreSQL, Supabase).
--
-- Как запустить: Supabase → SQL Editor → New query → вставить весь файл → Run.
-- Скрипт можно запускать повторно: старые таблицы удаляются и создаются заново
-- с начальными данными (это как POST /api/__reset, только для базы).
--
-- Сервер theatre-server.js подключается к базе по строке DATABASE_URL.
-- Ограничения в таблицах повторяют проверки сервера (422), поэтому даже
-- запись в обход API не испортит данные.
--
-- Связи:
--   театр 1:N спектакли, театр 1:N актёры труппы;
--   спектакль M:N жанры (show_genres), спектакль M:N актёры (show_actors);
--   зритель 1:1 карта зрителя (cards.spectator_id уникален);
--   зритель 1:N брони, спектакль 1:N брони;
--   пользователь-зритель 1:1 зритель (users.spectator_id).
--
-- Удаление «в корзину» — это заполненный deleted_at, запись остаётся.
-- Внешние ключи проверяются в конце транзакции (deferrable initially deferred):
-- сервер сохраняет все изменения запроса одной транзакцией, и порядок строк
-- внутри неё не важен.

drop table if exists refresh_tokens, users, bookings, cards, show_actors, show_genres,
  shows, spectators, actors, genres, theatres cascade;

create table theatres (
  id          integer generated by default as identity primary key,
  name        varchar(80)  not null check (length(trim(name)) >= 2),
  city        varchar(50)  not null check (length(trim(city)) >= 2),
  address     varchar(120) not null check (length(trim(address)) >= 5),
  hall_seats  integer not null check (hall_seats between 1 and 10000),
  founded     integer not null check (founded >= 1500),
  created_at  timestamptz not null default now(),
  deleted_at  timestamptz
);
-- в одном городе не может быть двух театров с одинаковым названием
create unique index theatres_name_city_key on theatres (lower(name), lower(city));

create table genres (
  id          integer generated by default as identity primary key,
  name        varchar(40)  not null check (length(trim(name)) >= 2),
  description varchar(300) not null default '',
  created_at  timestamptz not null default now(),
  deleted_at  timestamptz
);
create unique index genres_name_key on genres (lower(name));

create table actors (
  id          integer generated by default as identity primary key,
  last_name   varchar(50) not null check (length(trim(last_name)) >= 2),
  first_name  varchar(50) not null check (length(trim(first_name)) >= 2),
  country     varchar(50) not null check (length(trim(country)) >= 2),
  birth_year  integer not null check (birth_year >= 1900),
  theatre_id  integer not null references theatres (id) deferrable initially deferred,
  created_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

create table shows (
  id              integer generated by default as identity primary key,
  title           varchar(100) not null check (length(trim(title)) >= 2),
  code            varchar(7)   not null unique check (code ~ '^SP-[0-9]{4}$'),
  -- местное время театра, поэтому без часового пояса
  date            timestamp not null,
  duration        integer not null check (duration between 30 and 300),   -- минуты
  price           integer not null check (price between 1 and 50000),     -- рубли
  theatre_id      integer not null references theatres (id) deferrable initially deferred,
  seats_total     integer not null check (seats_total between 1 and 5000),
  seats_available integer not null check (seats_available between 0 and seats_total),
  created_at      timestamptz not null default now(),
  deleted_at      timestamptz
);

-- многие ко многим: у спектакля несколько жанров и несколько актёров
create table show_genres (
  show_id   integer not null references shows (id) on delete cascade deferrable initially deferred,
  genre_id  integer not null references genres (id) deferrable initially deferred,
  primary key (show_id, genre_id)
);

create table show_actors (
  show_id   integer not null references shows (id) on delete cascade deferrable initially deferred,
  actor_id  integer not null references actors (id) deferrable initially deferred,
  primary key (show_id, actor_id)
);

create table spectators (
  id          integer generated by default as identity primary key,
  last_name   varchar(50)  not null check (length(trim(last_name)) >= 2),
  first_name  varchar(50)  not null check (length(trim(first_name)) >= 2),
  email       varchar(100) not null check (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  phone       varchar(12)  not null check (phone ~ '^\+7[0-9]{10}$'),
  created_at  timestamptz not null default now(),
  deleted_at  timestamptz
);
create unique index spectators_email_key on spectators (lower(email));

-- один к одному: у зрителя одна карта, карта принадлежит одному зрителю
create table cards (
  id            integer generated by default as identity primary key,
  spectator_id  integer not null unique references spectators (id) on delete cascade deferrable initially deferred,
  number        char(6) not null unique check (number ~ '^[0-9]{6}$'),
  issued_at     date    not null,
  discount      integer not null check (discount between 0 and 50),        -- проценты
  created_at    timestamptz not null default now(),
  deleted_at    timestamptz
);

-- бронь держится 3 дня; active → paid / cancelled (кассир) или expired (срок вышел)
create table bookings (
  id            integer generated by default as identity primary key,
  spectator_id  integer not null references spectators (id) deferrable initially deferred,
  show_id       integer not null references shows (id) deferrable initially deferred,
  seats         integer not null check (seats between 1 and 10),
  status        varchar(10) not null default 'active'
                  check (status in ('active', 'paid', 'cancelled', 'expired')),
  extended      boolean not null default false,                         -- продлевали ли
  expires_at    timestamptz not null,
  closed_at     timestamptz,
  created_at    timestamptz not null default now(),
  deleted_at    timestamptz
);
create index bookings_show_idx on bookings (show_id);
create index bookings_spectator_idx on bookings (spectator_id);

-- пароли не храню: только sha256(пароль + ключ сервера)
create table users (
  id             integer generated by default as identity primary key,
  username       text not null check (username ~ '^[A-Za-z0-9_.-]{3,}$'),
  password_hash  char(64) not null,
  full_name      text not null,
  email          text not null,
  role           varchar(10) not null default 'viewer'
                   check (role in ('viewer', 'cashier', 'admin')),
  spectator_id   integer references spectators (id) on delete set null deferrable initially deferred,
  created_at     timestamptz not null default now(),
  deleted_at     timestamptz
);
create unique index users_username_key on users (lower(username));

-- выданные токены обновления: при выходе или обновлении токен удаляется
create table refresh_tokens (
  token       text primary key,
  created_at  timestamptz not null default now()
);

