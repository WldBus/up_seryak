Show _show(
  int id,
  String title,
  int theatreId,
  List<int> genreIds,
  DateTime date,
  int duration,
  int price,
  int total,
  int available,
) {
  return Show(
    id: id,
    title: title,
    code: 'SP-${1000 + id}',
    date: date,
    duration: duration,
    price: price,
    theatreId: theatreId,
    genreIds: genreIds,
    // играют актёры из труппы этого же театра
    actorIds: [theatreId * 2 - 1, if (id.isEven) theatreId * 2],
    seatsTotal: total,
    seatsAvailable: available,
  );
}

